"""Resolve the CPU runtime for both production architectures without running wheels."""
import datetime
import os
from pathlib import Path
import re
import subprocess
import tempfile

INDEX = "https://download.pytorch.org/whl/cpu"
ROOT = Path(__file__).resolve().parent
PLATFORMS = ("x86_64-manylinux_2_28", "aarch64-manylinux_2_28")


def parse_lock(text):
    records = {}
    current = None
    for line in text.splitlines():
        if not line.strip() or line.startswith("--index-url"):
            continue
        match = re.fullmatch(r"([\w-]+)==([\w.+-]+)(?: \\)?", line)
        if match:
            current = (match[1], match[2])
            records[current] = set()
            continue
        match = re.fullmatch(r"\s+--hash=sha256:([0-9a-f]{64})(?: \\)?", line)
        if not match or current is None:
            raise RuntimeError("Неподдерживаемый формат lock; проверьте вывод uv.")
        records[current].add(match[1])
    if not records or any(not hashes for hashes in records.values()):
        raise RuntimeError("В lock отсутствуют зависимости или хэши.")
    return records


def main():
    environment = {key: value for key, value in os.environ.items() if key not in {"UV_INDEX", "UV_DEFAULT_INDEX", "UV_INDEX_URL", "UV_EXTRA_INDEX_URL", "UV_FIND_LINKS"}}
    records = None
    with tempfile.TemporaryDirectory(prefix="pulse-tts-lock-") as folder:
        constraint = Path(folder) / "amd64.txt"
        for platform in PLATFORMS:
            command = ["uv", "--no-config", "pip", "compile", str(ROOT / "requirements.in"), "--python-version", "3.12", "--python-platform", platform, "--index-url", INDEX, "--generate-hashes", "--only-binary=:all:", "--no-header", "--no-annotate", "--emit-index-url"]
            if records is not None:
                command += ["--constraint", str(constraint)]
            result = subprocess.run(command, env=environment, check=True, capture_output=True, text=True)
            parsed = parse_lock(result.stdout)
            if records is None:
                records = parsed
                constraint.write_text(result.stdout)
            else:
                if records.keys() != parsed.keys():
                    raise RuntimeError("Набор версий/зависимостей различается между amd64 и arm64.")
                for name, hashes in parsed.items():
                    records[name].update(hashes)
    date = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
    lines = [f"# Lock date: {date}; CPython 3.12, Linux amd64 + arm64.", "# Generated by: python3 infra/tts/update_lock.py", f"--index-url {INDEX}", ""]
    for (name, version), hashes in sorted(records.items()):
        lines.append(f"{name}=={version} \\")
        ordered = sorted(hashes)
        lines.extend(f"    --hash=sha256:{digest}" + (" \\" if index < len(ordered) - 1 else "") for index, digest in enumerate(ordered))
    (ROOT / "requirements.txt").write_text("\n".join(lines) + "\n")
    print(f"Lock: {len(records)} пакетов, обе архитектуры; SHA-256 получены из CPU-индекса.")


if __name__ == "__main__":
    main()
