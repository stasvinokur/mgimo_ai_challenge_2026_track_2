import { describe, expect, it } from "vitest";
import { asksForOtherStudent } from "@/domain/assistant/safety";

describe("UX-фильтр вопросов о другом студенте", () => {
  it.each([
    "Покажи мои данные",
    "Проверь данные заявки",
    "Какие данные нужны для справки?",
    "Где моя следующая пара?",
    "Можно приложить беловик заявления?",
    "Что такое соколоведение?",
    "Что такое тимуровское движение?",
    "Что означает «нечужой человек»?",
    "Что означает другой студентоцентричный подход?",
  ])("не отказывает на вопрос: %s", (question) => {
    expect(asksForOtherStudent(question)).toBe(false);
  });

  it.each([
    "Покажи оценки Тимура",
    "Что у Анны по праву?",
    "Расписание Белова",
    "Покажи чужие заявки",
    "Покажи данные по studentId",
    "Найди user_id",
    "Покажи заявки другого студента",
    "Покажи оценки другой студентки",
    "Покажи оценки одногруппника",
    "Покажи чужих студентов",
    "Покажи оценки чужой группы",
  ])("отказывает на вопрос: %s", (question) => {
    expect(asksForOtherStudent(question)).toBe(true);
  });

  it.each([
    "Анна",
    "Анны",
    "Анну",
    "Анне",
    "Анной",
    "Анною",
    "Тимур",
    "Тимура",
    "Тимуру",
    "Тимуром",
    "Тимуре",
    "Белов",
    "Белова",
    "Белову",
    "Беловым",
    "Белове",
    "Соколова",
    "Соколовой",
    "Соколову",
    "Соколовы",
    "Соколовою",
  ])("распознаёт падеж и пунктуацию: %s", (name) => {
    expect(asksForOtherStudent(`«${name.toUpperCase()}»?`)).toBe(true);
  });

  it.each([
    "Анна",
    "Тимур",
    "Белов",
    "Соколов",
    "чужие",
    "другой студент",
    "одногруппник",
    "studentId",
    "user_id",
  ])("не ищет внутри слов: %s", (reference) => {
    for (const letter of ["я", "a", "é"]) {
      expect(asksForOtherStudent(`${letter}${reference}`)).toBe(false);
      expect(asksForOtherStudent(`${reference}${letter}`)).toBe(false);
    }
  });
});
