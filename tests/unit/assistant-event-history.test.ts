import { expect, it } from "vitest";
import { resolveEventDates } from "@/application/assistant/event-fields";

it.each([
  ["15–16 ноября 2026", "2026-11-15", "2026-11-16"],
  ["Исправь даты: 17–18 ноября 2026", "2026-11-17", "2026-11-18"],
  ["2026-11-17 — 2026-11-18", "2026-11-17", "2026-11-18"],
  ["17 ноября 2026", "2026-11-17", "2026-11-17"],
])(
  "явный период последнего сообщения важнее прежних дат: %s",
  (question, dateFrom, dateTo) => {
    expect(
      resolveEventDates(question, ["Еду на хакатон 15–16 ноября 2026"]),
    ).toEqual({ dateFrom, dateTo });
  },
);

it("полный ответ после уточнения года сохраняет повторённый период", () => {
  expect(
    resolveEventDates("15–16 ноября 2026", [
      "Еду на хакатон 15–16 ноября, что с парами?",
    ]),
  ).toEqual({ dateFrom: "2026-11-15", dateTo: "2026-11-16" });
});

it("ответ одним годом дополняет период мероприятия из истории", () => {
  expect(
    resolveEventDates("2026", ["Еду на хакатон 15–16 ноября, что с парами?"]),
  ).toEqual({ dateFrom: "2026-11-15", dateTo: "2026-11-16" });
});

it("последние день и месяц дополняются годом мероприятия из истории", () => {
  expect(
    resolveEventDates("17–18 ноября", ["Еду на хакатон 15–16 ноября 2026"]),
  ).toEqual({ dateFrom: "2026-11-17", dateTo: "2026-11-18" });
});

it.each(["Экзамен будет в 2027 году", "Экзамен будет 20 ноября 2027"])(
  "год постороннего вопроса не подменяет год мероприятия: %s",
  (unrelated) => {
    expect(
      resolveEventDates("17–18 ноября", [
        "Еду на хакатон 15–16 ноября 2026",
        unrelated,
      ]),
    ).toEqual({ dateFrom: "2026-11-17", dateTo: "2026-11-18" });
  },
);

it("ответ годом не заимствует день и месяц из постороннего вопроса", () => {
  expect(
    resolveEventDates("2026", [
      "Еду на хакатон 15–16 ноября",
      "Экзамен будет 20 ноября 2027",
    ]),
  ).toEqual({ dateFrom: "2026-11-15", dateTo: "2026-11-16" });
});

it("ближайшее исправление года важнее старого периода", () => {
  expect(
    resolveEventDates("17–18 ноября", [
      "Еду на хакатон 15–16 ноября 2025",
      "Исправь даты: 15–16 ноября 2026",
    ]),
  ).toEqual({ dateFrom: "2026-11-17", dateTo: "2026-11-18" });
});

it("предыдущий ответ только годом дополняет новые день и месяц", () => {
  expect(
    resolveEventDates("17–18 ноября", ["Еду на хакатон 15–16 ноября", "2026"]),
  ).toEqual({ dateFrom: "2026-11-17", dateTo: "2026-11-18" });
});

it.each([
  "17–18 ноября 2026 или 20–21 ноября 2026",
  "17–18 ноября 2026 и 20 декабря 2026",
  "17–18 ноября 2026, 2026-11-20 — 2026-11-21",
  "2026-11-17 — 2026-11-18, 20 ноября 2026",
  "17–18 ноября 2026 или 2027",
  "2026-11-17, 2026-11-18",
  "31 ноября 2026",
  "2026-11-31",
  "18–17 ноября 2026",
  "1–16 ноября 2026",
])(
  "ошибка последнего периода не заменяется прежним периодом: %s",
  (question) => {
    expect(
      resolveEventDates(question, ["Еду на хакатон 15–16 ноября 2026"]),
    ).toBeNull();
  },
);

it.each([
  { question: "17–18 ноября", history: [] },
  {
    question: "17–18 ноября",
    history: ["Еду на хакатон 15–16 ноября 2026 или 2027"],
  },
  {
    question: "2026",
    history: ["Еду на хакатон 15–16 ноября или 20–21 ноября"],
  },
  { question: "2026", history: ["Еду на хакатон 31 ноября"] },
  { question: "скоро", history: ["Еду на хакатон 15–16 ноября 2026"] },
])("не угадывает недостающие части: $question", ({ question, history }) => {
  expect(resolveEventDates(question, history)).toBeNull();
});
